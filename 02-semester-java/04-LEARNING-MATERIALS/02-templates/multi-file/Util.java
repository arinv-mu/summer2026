package com.example;

/**
 * Utility class with helper methods.
 */
public class Util {
    public int add(int a, int b) {
        return a + b;
    }
    
    public int subtract(int a, int b) {
        return a - b;
    }
    
    public String greet(String name) {
        return "Hello, " + name + "!";
    }
}
