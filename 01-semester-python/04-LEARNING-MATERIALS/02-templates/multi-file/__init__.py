# Multi-file Python Package Example
#
# Directory structure:
# mypackage/
# ├── __init__.py      (makes it a package)
# ├── main.py          (entry point)
# └── utils.py         (helper functions)

# Usage:
# 1. Put your files in a folder named 'mypackage'
# 2. Run from parent directory: python -m mypackage.main
